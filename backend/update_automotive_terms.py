def update_automotive_terms():
    """정비 용어 데이터 업데이트"""
    db = SessionLocal()

    try:
        print("=" * 60)
        print("자동차 정비 용어 데이터베이스 업데이트 시작")
        print("=" * 60)

        total_parts = len(AUTOMOTIVE_TERMS)
        total_aliases = sum(len(aliases) for _, aliases in AUTOMOTIVE_TERMS)

        print(f"\n추가 예정: {total_parts}개 부품명, {total_aliases}개 별칭")
        print()

        added_parts = 0
        added_aliases = 0
        updated_aliases = 0

        for formal_name, aliases in AUTOMOTIVE_TERMS:
            # 정식 부품명 생성 또는 조회
            part = crud.get_or_create_part(db, formal_name)

            part_existed = part.id is not None
            if not part_existed:
                added_parts += 1
                print(f"✓ 새 부품 추가: {formal_name}")

            # 별칭 매핑 생성
            for alias in aliases:
                if alias != formal_name:  # 중복 방지
                    mapping = crud.create_or_update_mapping(
                        db,
                        alias,
                        formal_name,
                        confidence_score=1.0
                    )

                    # 새로 추가되었는지 확인 (간단한 휴리스틱)
                    if mapping.usage_count == 1:
                        added_aliases += 1
                        print(f"  → 별칭 추가: '{alias}' → '{formal_name}'")
                    else:
                        updated_aliases += 1
                        print(f"  ↻ 별칭 업데이트: '{alias}' → '{formal_name}'")

        print()
        print("=" * 60)
        print("업데이트 완료!")
        print("=" * 60)
        print(f"✓ 새로 추가된 부품명: {added_parts}개")
        print(f"✓ 새로 추가된 별칭: {added_aliases}개")
        print(f"✓ 업데이트된 별칭: {updated_aliases}개")
        print()

        # 현재 DB 통계
        from app.db.models import Part, PartMapping
        total_parts_in_db = db.query(Part).count()
        total_mappings_in_db = db.query(PartMapping).count()

        print(f"현재 데이터베이스 통계:")
        print(f"  - 전체 부품명: {total_parts_in_db}개")
        print(f"  - 전체 별칭 매핑: {total_mappings_in_db}개")
        print()

    except Exception as e:
        print(f"\n❌ 에러 발생: {e}")
        import traceback
        traceback.print_exc()
        db.rollback()
    finally:
        db.close()


